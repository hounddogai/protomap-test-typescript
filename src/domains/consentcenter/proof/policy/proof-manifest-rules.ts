import { ProofManifest } from "./proof-manifest.js";

/** A rule a proof manifest must pass. Check returns its problems, or none. */
export interface ProofManifestRule {
  check(item: ProofManifest): string[];
}

export class ProofManifestUpdatedAtRangeRule implements ProofManifestRule {
  min: number;
  max: number;

  constructor(min: number, max: number) {
    this.min = min;
    this.max = max;
  }

  check(item: ProofManifest): string[] {
    const value = item.updatedAt;
    const problems: string[] = [];
    if (value < this.min) {
      problems.push(`updated at ${value} is below ${this.min}`);
    }
    if (value > this.max) {
      problems.push(`updated at ${value} is above ${this.max}`);
    }
    return problems;
  }
}

export class ProofManifestVersionRangeRule implements ProofManifestRule {
  min: number;
  max: number;

  constructor(min: number, max: number) {
    this.min = min;
    this.max = max;
  }

  check(item: ProofManifest): string[] {
    const value = item.version;
    const problems: string[] = [];
    if (value < this.min) {
      problems.push(`version ${value} is below ${this.min}`);
    }
    if (value > this.max) {
      problems.push(`version ${value} is above ${this.max}`);
    }
    return problems;
  }
}

export class ProofManifestWindowDaysRangeRule implements ProofManifestRule {
  min: number;
  max: number;

  constructor(min: number, max: number) {
    this.min = min;
    this.max = max;
  }

  check(item: ProofManifest): string[] {
    const value = item.windowDays;
    if (value < this.min || value > this.max) return [`window days ${value} is outside ${this.min} to ${this.max}`];
    return [];
  }
}

/** Runs every rule of a proof manifest. */
export class ProofManifestValidator {
  rules: ProofManifestRule[];

  constructor(rules: ProofManifestRule[]) {
    this.rules = rules;
  }

  validate(item: ProofManifest): string[] {
    const problems: string[] = [];
    for (const rule of this.rules) {
      const found = rule.check(item);
      if (found.length === 0) continue;
      for (const problem of found) {
        problems.push(`${item.code}: ${problem}`);
      }
    }
    return problems;
  }

  requireValid(item: ProofManifest): void {
    const problems = this.validate(item);
    if (problems.length > 0) {
      throw new Error(`${item.label()} is invalid: ${problems.join("; ")}`);
    }
  }

  validateAll(items: ProofManifest[]): Map<string, string[]> {
    const report = new Map<string, string[]>();
    for (const item of items) {
      const problems = this.validate(item);
      if (problems.length > 0) {
        report.set(item.code, problems);
      }
    }
    return report;
  }
}

export function defaultProofManifestValidator(): ProofManifestValidator {
  return new ProofManifestValidator(
    [
      new ProofManifestUpdatedAtRangeRule(80, 120),
      new ProofManifestVersionRangeRule(80, 86400),
      new ProofManifestWindowDaysRangeRule(1000, 86400),
    ],
  );
}
