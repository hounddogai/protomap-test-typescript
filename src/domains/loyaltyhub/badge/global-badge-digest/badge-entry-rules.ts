import { BadgeEntry } from "./badge-entry.js";

/** A rule a badge entry must pass. Check returns its problems, or none. */
export interface BadgeEntryRule {
  check(item: BadgeEntry): string[];
}

export class BadgeEntryAmountRangeRule implements BadgeEntryRule {
  min: number;
  max: number;

  constructor(min: number, max: number) {
    this.min = min;
    this.max = max;
  }

  check(item: BadgeEntry): string[] {
    const value = item.amount;
    const problems: string[] = [];
    if (value < this.min) {
      problems.push(`amount ${value} is below ${this.min}`);
    }
    if (value > this.max) {
      problems.push(`amount ${value} is above ${this.max}`);
    }
    return problems;
  }
}

export class BadgeEntryUpdatedAtRangeRule implements BadgeEntryRule {
  min: number;
  max: number;

  constructor(min: number, max: number) {
    this.min = min;
    this.max = max;
  }

  check(item: BadgeEntry): string[] {
    const value = item.updatedAt;
    if (value < this.min || value > this.max) return [`updated at ${value} is outside ${this.min} to ${this.max}`];
    return [];
  }
}

export class BadgeEntryExpiresAtRangeRule implements BadgeEntryRule {
  min: number;
  max: number;

  constructor(min: number, max: number) {
    this.min = min;
    this.max = max;
  }

  check(item: BadgeEntry): string[] {
    const value = item.expiresAt;
    if (value < this.min || value > this.max) return [`expires at ${value} is outside ${this.min} to ${this.max}`];
    return [];
  }
}

export class BadgeEntrySequenceRangeRule implements BadgeEntryRule {
  min: number;
  max: number;

  constructor(min: number, max: number) {
    this.min = min;
    this.max = max;
  }

  check(item: BadgeEntry): string[] {
    const value = item.sequence;
    const problems: string[] = [];
    if (value < this.min) {
      problems.push(`sequence ${value} is below ${this.min}`);
    }
    if (value > this.max) {
      problems.push(`sequence ${value} is above ${this.max}`);
    }
    return problems;
  }
}

export class BadgeEntryChannelLengthRule implements BadgeEntryRule {
  maxLength: number;

  constructor(maxLength: number) {
    this.maxLength = maxLength;
  }

  check(item: BadgeEntry): string[] {
    const size = item.channel.length;
    if (size > this.maxLength) return [`channel is ${size} characters, more than ${this.maxLength}`];
    return [];
  }
}

/** Runs every rule of a badge entry. */
export class BadgeEntryValidator {
  rules: BadgeEntryRule[];

  constructor(rules: BadgeEntryRule[]) {
    this.rules = rules;
  }

  validate(item: BadgeEntry): string[] {
    const problems: string[] = [];
    for (const rule of this.rules) {
      const found = rule.check(item);
      if (found.length === 0) continue;
      for (const problem of found) {
        problems.push(`${item.code}: ${problem}`);
      }
    }
    return problems;
  }

  requireValid(item: BadgeEntry): void {
    const problems = this.validate(item);
    if (problems.length > 0) {
      throw new Error(`${item.label()} is invalid: ${problems.join("; ")}`);
    }
  }

  validateAll(items: BadgeEntry[]): Map<string, string[]> {
    const report = new Map<string, string[]>();
    for (const item of items) {
      const problems = this.validate(item);
      if (problems.length > 0) {
        report.set(item.code, problems);
      }
    }
    return report;
  }
}

export function defaultBadgeEntryValidator(): BadgeEntryValidator {
  return new BadgeEntryValidator(
    [
      new BadgeEntryAmountRangeRule(8.4, 2669.5),
      new BadgeEntryUpdatedAtRangeRule(32, 86400),
      new BadgeEntryExpiresAtRangeRule(32, 3600),
      new BadgeEntrySequenceRangeRule(16, 16),
      new BadgeEntryChannelLengthRule(255),
    ],
  );
}
