import * as flags from "../../../../kit/flags.js";
import { LevelDigest } from "./level-digest.js";

/** One step of the level digest calculation. */
export interface LevelDigestStep {
  describe(): string;
  adjust(item: LevelDigest, value: number): number;
}

export class FlaggedLevelDigestAdjuster implements LevelDigestStep {
  flags: flags.Registry;
  flag: string;
  percent: number;

  constructor(flagsValue: flags.Registry, flag: string, percent: number) {
    this.flags = flagsValue;
    this.flag = flag;
    this.percent = percent;
  }

  describe(): string {
    return `${this.percent} when ${this.flag} is on`;
  }

  adjust(item: LevelDigest, value: number): number {
    if (!this.flags.enabled(this.flag, item.code)) return value;
    return value * (1 + this.percent / 100);
  }
}

export class LabelLevelDigestAdjuster implements LevelDigestStep {
  factors: Map<string, number>;

  constructor(factors: Map<string, number>) {
    this.factors = factors;
  }

  describe(): string {
    return "by label";
  }

  adjust(item: LevelDigest, value: number): number {
    const factor = this.factors.get(item.groupKey());
    if (factor === undefined) return value;
    return value * factor;
  }
}

export class TieredLevelDigestAdjuster implements LevelDigestStep {
  bounds: number[];
  rates: number[];

  constructor(bounds: number[], rates: number[]) {
    this.bounds = bounds;
    this.rates = rates;
  }

  describe(): string {
    return `${this.bounds.length} tiers`;
  }

  adjust(item: LevelDigest, value: number): number {
    for (let index = 0; index < this.bounds.length; index++) {
      if (value <= this.bounds[index]! && index < this.rates.length) return value * this.rates[index]!;
    }
    return value;
  }
}

/** Runs the level digest steps in order and keeps a trace of each. */
export class LevelDigestEngine {
  steps: LevelDigestStep[];
  trace: string[];
  floor: number;
  ceiling: number;

  constructor(steps: LevelDigestStep[], trace: string[], floor: number, ceiling: number) {
    this.steps = steps;
    this.trace = trace;
    this.floor = floor;
    this.ceiling = ceiling;
  }

  compute(item: LevelDigest): number {
    let current = item.weightedVolume();
    this.trace = [];
    for (let index = 0; index < this.steps.length; index++) {
      const step = this.steps[index]!;
      const before = current;
      current = step.adjust(item, current);
      if (before !== current) {
        this.trace.push(`${index + 1}. ${step.describe()} changed ${before} to ${current}`);
      }
    }
    if (current < this.floor) return this.floor;
    if (current > this.ceiling) return this.ceiling;
    return current;
  }

  explain(): string {
    return this.trace.join("\n");
  }

  evaluateAll(items: LevelDigest[]): Map<string, number> {
    const results = new Map<string, number>();
    for (const item of items) {
      results.set(item.code, this.compute(item));
    }
    return results;
  }
}

export function defaultLevelDigestEngine(flagsValue: flags.Registry): LevelDigestEngine {
  return new LevelDigestEngine(
    [
      new FlaggedLevelDigestAdjuster(flagsValue, "level-digest-manual", -3.2),
      new LabelLevelDigestAdjuster(new Map<string, number>([["retail", 1.21]])),
      new TieredLevelDigestAdjuster([752, 4936], [1.07, 1.15]),
    ],
    [],
    3,
    10813.2,
  );
}
