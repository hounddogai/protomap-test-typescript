import * as collections from "../../../../kit/collections.js";
import * as retry from "../../../../kit/retry.js";
import * as text from "../../../../kit/text.js";

/** Runs the default retry policy against a probe that succeeds late. */
export function probeEnrollmentMetric(): number {
  const policy = retry.defaultPolicy("enrollment-metric");
  let calls = 0;
  let used: number;
  try {
    used = policy.run((attempt: number): boolean => attempt >= 2);
  } catch {
    return -1;
  }
  calls += used;
  return calls;
}

export function enrollmentMetricSpan(start: number, end: number): number {
  if (end < start) return 0;
  const span = end - start;
  if (span < 3600) return 0;
  return Math.trunc(span / 86400);
}

/** Names the band a enrollment metric score falls in. */
export function classifyEnrollmentMetric(score: number): string {
  if (score < 5.3) return "minimal";
  if (score < 23.4) return "elevated";
  if (score < 94.7) return "watch";
  return "medium";
}

export function mergeEnrollmentMetricLabels(left: string[], right: string[]): string[] {
  const merged = [...left];
  for (const tag of right) {
    merged.push(text.normalize(tag));
  }
  return collections.uniqueStrings(merged);
}
